// Generates and checks the 72 canonical top-level directories described in
// 01_governance/structure.json.
//
//   node tools/structure.mjs --write   regenerate every README.md
//   node tools/structure.mjs --check   fail on any drift (run by tools/verify.mjs)
//
// A README.md without the generated marker is never overwritten: hand-written
// work is preserved and reported instead.
import { readFileSync, writeFileSync, existsSync, mkdirSync, readdirSync, statSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join, relative } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const MARKER = '<!-- generated by tools/structure.mjs from 01_governance/structure.json -->';
const mode = process.argv.includes('--write') ? 'write' : process.argv.includes('--check') ? 'check' : null;
if (!mode) {
  console.error('usage: node tools/structure.mjs --write | --check');
  process.exit(2);
}

const manifest = JSON.parse(readFileSync(join(root, '01_governance/structure.json'), 'utf8'));
const catalog = JSON.parse(readFileSync(join(root, 'register/catalog.json'), 'utf8'));
const dirs = manifest.directories;
const errors = [];

// --- traceability.csv (RFC 4180) ---
function parseCsv(text) {
  const rows = [];
  let row = [], cell = '', q = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (q) {
      if (c === '"' && text[i + 1] === '"') { cell += '"'; i++; }
      else if (c === '"') q = false;
      else cell += c;
    } else if (c === '"') q = true;
    else if (c === ',') { row.push(cell); cell = ''; }
    else if (c === '\n') { row.push(cell.replace(/\r$/, '')); rows.push(row); row = []; cell = ''; }
    else cell += c;
  }
  if (cell || row.length) { row.push(cell); rows.push(row); }
  return rows;
}
const csv = parseCsv(readFileSync(join(root, 'docs/traceability.csv'), 'utf8'));
const header = csv[0];
const col = (n) => header.indexOf(n);
const STATUSES = ['implemented and tested', 'implemented but not fully tested', 'specified only', 'blocked by an external dependency'];
const byDomainName = new Map();
for (const r of csv.slice(1)) {
  const counts = byDomainName.get(r[col('domain')]) ?? [0, 0, 0, 0];
  const i = STATUSES.indexOf(r[col('status')]);
  if (i < 0) errors.push(`traceability.csv: unknown status "${r[col('status')]}" for ${r[col('feature_id')]}`);
  else counts[i]++;
  byDomainName.set(r[col('domain')], counts);
}
const domainBySlug = new Map(catalog.domains.map((d) => [d.slug, d]));

// --- manifest checks ---
if (dirs.length !== 72) errors.push(`manifest lists ${dirs.length} directories, expected 72`);
dirs.forEach((d, i) => {
  const n = String(i + 1).padStart(2, '0');
  if (!d.id.startsWith(n + '_')) errors.push(`directory ${i + 1} is ${d.id}; expected prefix ${n}_`);
});
const owners = new Map();
for (const d of dirs) for (const s of d.domains) {
  if (!domainBySlug.has(s)) errors.push(`${d.id}: unknown register domain ${s}`);
  if (owners.has(s)) errors.push(`domain ${s} assigned to both ${owners.get(s)} and ${d.id}`);
  owners.set(s, d.id);
}
for (const s of domainBySlug.keys()) if (!owners.has(s)) errors.push(`register domain ${s} is not assigned to any directory`);

const link = (from, target) => relative(join(root, from), join(root, target)).replaceAll('\\', '/');

function readme(d) {
  const lines = [MARKER, '', `# ${d.id.slice(0, 2)} · ${d.title}`, '', `**Purpose:** ${d.purpose}`, '', `**Owner:** ${d.owner}`, ''];
  lines.push('## Where the implementation lives', '');
  if (d.implementedBy.length === 0) lines.push('Nothing is implemented for this area yet. See *Known gaps*.');
  for (const p of d.implementedBy) lines.push(`- [${p}](${link(d.id, p)})`);
  lines.push('');
  if (d.artifacts.length) {
    lines.push('## Artifacts in this directory', '');
    for (const a of d.artifacts) lines.push(`- [${a}](${a})`);
    lines.push('');
  }
  lines.push('## Register coverage', '');
  if (d.domains.length === 0) {
    lines.push('No register domain is owned here; this directory holds cross-cutting code used by the domains below it.');
  } else {
    lines.push('Feature counts by honest status, from [docs/traceability.csv](' + link(d.id, 'docs/traceability.csv') + ').', '');
    lines.push('| Domain | Features | Tested | Not fully tested | Specified only | Blocked |', '|---|---|---|---|---|---|');
    for (const s of d.domains) {
      const dom = domainBySlug.get(s);
      if (!dom) continue;
      const c = byDomainName.get(dom.name) ?? [0, 0, 0, 0];
      lines.push(`| [${dom.name}](${link(d.id, `docs/domains/${s}.md`)}) | ${c.reduce((a, b) => a + b, 0)} | ${c.join(' | ')} |`);
    }
  }
  lines.push('', '## Known gaps', '', d.gaps || 'None recorded beyond the per-feature gaps in the traceability matrix.', '');
  return lines.join('\n');
}

for (const d of dirs) {
  const dir = join(root, d.id);
  const file = join(dir, 'README.md');
  const want = readme(d);
  for (const p of d.implementedBy) if (!existsSync(join(root, p))) errors.push(`${d.id}: implementedBy path ${p} does not exist`);
  for (const a of d.artifacts) if (!existsSync(join(dir, a))) errors.push(`${d.id}: artifact ${a} does not exist`);
  const have = existsSync(file) ? readFileSync(file, 'utf8').replaceAll('\r\n', '\n') : null;
  if (have !== null && !have.startsWith(MARKER)) {
    errors.push(`${d.id}/README.md is hand-written; not overwriting it`);
    continue;
  }
  if (mode === 'write') {
    mkdirSync(dir, { recursive: true });
    if (have !== want) writeFileSync(file, want);
  } else if (have !== want) {
    errors.push(`${d.id}/README.md is ${have === null ? 'missing' : 'stale'}; run node tools/structure.mjs --write`);
  }
}

// Every documentation path named in the traceability matrix must exist.
for (const p of new Set(csv.slice(1).map((r) => r[col('docs')]))) {
  const file = p.split('#')[0];
  if (file && !existsSync(join(root, file))) errors.push(`traceability.csv references missing document ${file}`);
}

// The release manifest must match the workspace version.
const cargoVersion = readFileSync(join(root, 'Cargo.toml'), 'utf8').match(/^version = "([^"]+)"/m)?.[1];
const release = JSON.parse(readFileSync(join(root, '01_governance/release/manifest.json'), 'utf8'));
if (release.workspace_version !== cargoVersion) errors.push(`release manifest says ${release.workspace_version}, Cargo.toml says ${cargoVersion}`);

// No unknown NN_ directories and no empty directories with an undefined purpose.
const ids = new Set(dirs.map((d) => d.id));
for (const name of readdirSync(root)) {
  if (/^\d\d_/.test(name) && statSync(join(root, name)).isDirectory() && !ids.has(name)) errors.push(`unexpected top-level directory ${name}`);
}
function empties(dir) {
  const items = readdirSync(dir);
  if (items.length === 0) errors.push(`empty directory ${relative(root, dir)}`);
  for (const i of items) if (statSync(join(dir, i)).isDirectory()) empties(join(dir, i));
}
for (const d of dirs) if (existsSync(join(root, d.id))) empties(join(root, d.id));

if (errors.length) {
  console.error(errors.map((e) => '  - ' + e).join('\n'));
  console.error(`\nstructure: ${errors.length} problem(s)`);
  process.exit(1);
}
console.log(`structure: ${dirs.length} canonical directories ${mode === 'write' ? 'written' : 'verified'}; ${owners.size} register domains assigned exactly once`);
