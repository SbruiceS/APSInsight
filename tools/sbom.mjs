// Software bill of materials and licence report.
//
//   node tools/sbom.mjs [--out target/sbom]
//
// Rust: `cargo tree` over the workspace for the host target (normal + build
// edges, i.e. what ships in the binaries). Web: production packages from
// web/package-lock.json. Writes CycloneDX 1.5 JSON per ecosystem plus a Markdown
// licence report, and exits 1 if any shipped dependency has a licence outside the
// allow-list or no declared licence.
import { spawnSync } from 'node:child_process';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const outArg = process.argv.indexOf('--out');
const out = join(root, outArg > 0 ? process.argv[outArg + 1] : 'target/sbom');
const ALLOW = new Set([
  'Apache-2.0', 'Apache-2.0 WITH LLVM-exception', 'MIT', 'BSD-2-Clause', 'BSD-3-Clause', 'ISC',
  'Unicode-3.0', 'Unicode-DFS-2016', 'Zlib', 'CC0-1.0', 'MPL-2.0', 'BSL-1.0', '0BSD',
]);

/** Evaluates an SPDX expression (AND binds tighter than OR; parentheses group;
 *  the legacy `A/B` form means A OR B) against the allow-list. */
export function allowed(expr) {
  if (!expr) return false;
  const tokens = expr.replaceAll('/', ' OR ').replace(/([()])/g, ' $1 ').trim().split(/\s+/);
  let i = 0;
  const atom = () => {
    if (tokens[i] === '(') {
      i++;
      const v = or();
      if (tokens[i++] !== ')') throw new Error('unbalanced');
      return v;
    }
    let id = tokens[i++];
    if (tokens[i] === 'WITH') { id += ' WITH ' + tokens[i + 1]; i += 2; }
    return ALLOW.has(id);
  };
  const and = () => { let v = atom(); while (tokens[i] === 'AND') { i++; v = atom() && v; } return v; };
  const or = () => { let v = and(); while (tokens[i] === 'OR') { i++; v = and() || v; } return v; };
  try {
    const v = or();
    return i === tokens.length && v;
  } catch {
    return false;
  }
}

if (process.argv.includes('--self-test')) {
  const cases = [['MIT', true], ['MIT OR GPL-3.0', true], ['GPL-3.0', false], ['(MIT OR Apache-2.0) AND Unicode-3.0', true],
    ['(MIT OR GPL-3.0) AND GPL-3.0', false], ['MIT AND GPL-3.0', false], ['MIT/Apache-2.0', true], ['Apache-2.0 WITH LLVM-exception', true], ['', false], ['(MIT', false]];
  for (const [e, want] of cases) if (allowed(e) !== want) { console.error('self-test failed: ' + e); process.exit(1); }
  console.log('sbom self-test: ' + cases.length + ' licence expressions ok');
  process.exit(0);
}

function rust() {
  const r = spawnSync('cargo', ['tree', '--workspace', '--prefix', 'none', '--edges', 'normal,build', '--format', '{p}|{l}'], {
    cwd: root, encoding: 'utf8', maxBuffer: 64 * 1024 * 1024,
  });
  if (r.status !== 0) {
    console.error(r.stderr);
    process.exit(r.status ?? 1);
  }
  const seen = new Map();
  for (const line of r.stdout.split('\n')) {
    const [pkg, license = ''] = line.trim().replace(/ \(\*\)$/, '').split('|');
    if (!pkg) continue;
    const m = pkg.match(/^(\S+) v(\S+)(?: \((.*)\))?/);
    if (!m) continue;
    const local = (m[3] ?? '').length > 0 && !m[3].startsWith('proc-macro');
    const key = `${m[1]}@${m[2]}`;
    if (!seen.has(key)) seen.set(key, { name: m[1], version: m[2], license: license.trim(), first_party: local && m[1].startsWith('apsi-') });
  }
  return [...seen.values()];
}

function web() {
  const lock = JSON.parse(readFileSync(join(root, 'web/package-lock.json'), 'utf8'));
  return Object.entries(lock.packages ?? {})
    .filter(([path, p]) => path.startsWith('node_modules/') && !p.dev && !p.devOptional)
    .map(([path, p]) => ({ name: path.slice(path.lastIndexOf('node_modules/') + 13), version: p.version, license: typeof p.license === 'string' ? p.license : '', first_party: false }));
}

function cyclonedx(name, comps, type) {
  return {
    bomFormat: 'CycloneDX',
    specVersion: '1.5',
    version: 1,
    metadata: { component: { type: 'application', name, version: '0.1.0' }, tools: [{ name: 'tools/sbom.mjs' }] },
    components: comps.map((c) => ({
      type: 'library',
      name: c.name,
      version: c.version,
      purl: `pkg:${type}/${c.name.replace('@', '%40')}@${c.version}`,
      licenses: c.license ? [{ expression: c.license }] : [],
    })),
  };
}

mkdirSync(out, { recursive: true });
const sets = [['rust', 'cargo', rust()], ['web', 'npm', web()]];
const problems = [];
let report = '# Dependency licence report\n\n> Generated by `node tools/sbom.mjs`.\n\n';
for (const [eco, type, all] of sets) {
  const third = all.filter((c) => !c.first_party).sort((a, b) => a.name.localeCompare(b.name));
  writeFileSync(join(out, `apsinsight-${eco}.cdx.json`), JSON.stringify(cyclonedx(`apsinsight-${eco}`, third, type), null, 2) + '\n');
  const counts = new Map();
  for (const c of third) {
    counts.set(c.license || '(none)', (counts.get(c.license || '(none)') ?? 0) + 1);
    if (!allowed(c.license)) problems.push(`${eco}: ${c.name}@${c.version} has licence "${c.license || 'none declared'}"`);
  }
  report += `## ${eco} (${third.length} third-party components)\n\n| Licence | Components |\n|---|---|\n`;
  for (const [l, n] of [...counts].sort((a, b) => b[1] - a[1])) report += `| ${l} | ${n} |\n`;
  report += '\n';
}
report += problems.length ? `## Problems\n\n${problems.map((p) => `- ${p}`).join('\n')}\n` : '## Problems\n\nNone: every shipped dependency has an allowed licence.\n';
writeFileSync(join(out, 'licence-report.md'), report);
if (problems.length) {
  console.error(problems.join('\n'));
  console.error(`\nsbom: ${problems.length} licence problem(s); see ${join(out, 'licence-report.md')}`);
  process.exit(1);
}
console.log(`sbom: ${sets.map(([e, , a]) => `${a.filter((c) => !c.first_party).length} ${e}`).join(', ')} components; written to ${out}`);
