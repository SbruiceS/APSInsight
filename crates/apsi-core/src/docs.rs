//! Generated per-domain documentation ("Documentation" family). `apsi docs generate`
//! writes these to `docs/domains/`; a test fails if the files drift from the code.

use crate::catalog::{Domain, catalog, features};
use crate::quality::{FORMULAS, LIMITATIONS, MISSING_DATA};
use crate::schema::{EntitySchema, FieldType};
use crate::traceability;
use std::fmt::Write as _;

fn type_label(t: &FieldType) -> String {
    match t {
        FieldType::Enum { values } => format!("enum({})", values.join(" \\| ")),
        FieldType::GeoPoint => "geo point (WGS 84)".into(),
        other => format!("{other:?}").to_lowercase(),
    }
}

pub fn domain_markdown(d: &Domain) -> String {
    let c = catalog();
    let mut s = String::new();
    let _ = writeln!(s, "# {}\n", d.name);
    let _ = writeln!(s, "> Generated by `apsi docs generate` from the feature register. Do not edit by hand.\n");
    let _ = writeln!(
        s,
        "Domain slug: `{}` · Domain #{} of {} · {} entity kinds · {} features\n",
        d.slug,
        d.index,
        c.domains.len(),
        d.entities.len(),
        c.capabilities.len()
    );
    let _ = writeln!(s, "## Purpose\n");
    let _ = writeln!(
        s,
        "Manage {} as tenant-scoped, versioned, auditable records with validation, search, quality indicators, retention, notifications, workflows and import/export.\n",
        d.entities.iter().map(|e| e.name.as_str()).collect::<Vec<_>>().join(", ")
    );
    let _ = writeln!(s, "## Entity kinds\n\n| Entity | Slug | Records API |\n|---|---|---|");
    for e in &d.entities {
        let _ = writeln!(s, "| {} | `{}` | `/api/v1/domains/{}/entities/{}/records` |", e.name, e.slug, d.slug, e.slug);
    }
    let schema = EntitySchema::default_for(&d.slug, "<entity>");
    let _ = writeln!(
        s,
        "\n## Schema (default v1, every entity kind)\n\nRecord fields: `id`, `tenant`, `domain`, `entity`, `schema_version`, `version`, `lifecycle` (draft|active|archived), `name` (required, 1..256 chars), `attributes`, `tags`, `source` {{system, id}}, `owner`, `legal_hold`, `created_at`, `updated_at`, `created_by`, `updated_by`, `archived_at`, `provenance[]`.\n\n| Attribute | Type | Required | Notes |\n|---|---|---|---|"
    );
    for f in &schema.fields {
        let _ =
            writeln!(s, "| `{}` | {} | {} | {} |", f.name, type_label(&f.ty), if f.required { "yes" } else { "no" }, f.description.clone().unwrap_or_default());
    }
    let _ = writeln!(
        s,
        "\nAdditional attributes are accepted and preserved. Administrators publish later versions via `POST .../schemas`; breaking changes need `allow_breaking=true` and a migration.\n"
    );
    let _ = writeln!(s, "## Permissions\n\n| Operation | Viewer | Editor | Auditor | Admin |\n|---|---|---|---|---|");
    for (op, v, e, a, ad) in [
        ("read, search, export, quality, dashboards", "✓", "✓", "✓", "✓"),
        ("create, update, archive, bulk/import, notification rules, workflows", "", "✓", "", "✓"),
        ("restore archived, delete, legal hold, schemas, rules, retention, migrations", "", "", "", "✓"),
        ("audit log, metrics", "", "", "✓", "✓"),
    ] {
        let _ = writeln!(s, "| {op} | {v} | {e} | {a} | {ad} |");
    }
    let _ = writeln!(s, "\nAll access is scoped to the caller's tenant; records of other tenants are reported as not found.\n");
    let _ = writeln!(s, "## Failure modes\n\n| Code | HTTP | Retryable | Meaning |\n|---|---|---|---|");
    for (code, http, retry, meaning) in [
        ("invalid_input", 400, "no", "malformed request or identifier"),
        ("validation_failed", 422, "no", "schema or rule errors; `details` holds the machine-readable report"),
        ("not_found", 404, "no", "unknown domain, entity kind, record or version"),
        ("version_conflict", 409, "yes", "stale `expected_version`; reload and retry"),
        ("conflict", 409, "no", "duplicate source identity, idempotency key reuse, breaking schema"),
        ("legal_hold", 409, "no", "record is under legal hold"),
        ("lifecycle_violation", 422, "no", "transition not allowed or record archived"),
        ("unauthenticated", 401, "no", "missing or unknown token"),
        ("forbidden", 403, "no", "role or tenant does not permit the operation"),
        ("rate_limited", 429, "yes", "per-token budget exceeded; see Retry-After"),
        ("payload_too_large", 413, "no", "body > 16 MiB or > 10,000 bulk items"),
        ("storage_unavailable", 503, "yes", "persistence failed; the transaction was rolled back"),
    ] {
        let _ = writeln!(s, "| `{code}` | {http} | {retry} | {meaning} |");
    }
    let _ = writeln!(s, "\n## Quality indicators\n");
    for (k, v) in FORMULAS {
        let _ = writeln!(s, "- **{k}**: {v}");
    }
    let _ = writeln!(s, "\n{MISSING_DATA}\n\n{LIMITATIONS}\n");
    let _ = writeln!(
        s,
        "## Operational behavior\n\nEvery change runs in an all-or-nothing transaction, increments the record version, appends provenance and history, updates indexes, emits matching notifications and appends a hash-chained audit event. Metrics: `apsi_operations_total{{operation,domain=\"{}\",outcome}}`.\n",
        d.slug
    );
    let _ = writeln!(s, "## Features\n\n| ID | Capability | Status | Evidence | Gap |\n|---|---|---|---|---|");
    let first = (d.index - 1) * c.capabilities.len();
    for f in &features()[first..first + c.capabilities.len()] {
        let r = traceability::row(&f.id).expect("every feature has a trace row");
        let _ = writeln!(
            s,
            "| {} | {} | {} | {} | {} |",
            f.id,
            f.title,
            r.status_label,
            r.tests.first().map(String::as_str).unwrap_or("-"),
            r.gap.replace('|', "\\|")
        );
    }
    s
}

pub fn index_markdown() -> String {
    let c = catalog();
    let mut s = String::from("# Domain documentation\n\n> Generated by `apsi docs generate`.\n\n| # | Domain | Entity kinds | Features |\n|---|---|---|---|\n");
    for d in &c.domains {
        let first = (d.index - 1) * c.capabilities.len() + 1;
        let _ = writeln!(
            s,
            "| {} | [{}]({}.md) | {} | APSI-F{:04}–APSI-F{:04} |",
            d.index,
            d.name,
            d.slug,
            d.entities.len(),
            first,
            first + c.capabilities.len() - 1
        );
    }
    s
}
